using UnityEngine;

namespace UI
{
    /// <summary>
    /// Настройки для DrumCounter: скорость, плавность и размер выброса.
    /// </summary>
    [CreateAssetMenu(fileName = "DrumCounterSettings", menuName = "UI/DrumCounterSettings")]
    public class DrumCounterSettings : ScriptableObject
    {
        /// <summary>
        /// Потолок скорости прокрутки в единицах значения в секунду. Это ограничение сверху, а не средняя скорость:
        /// барабан разгоняется и тормозит, поэтому время пути больше, чем расстояние, делённое на потолок.
        /// </summary>
        [Tooltip("Потолок скорости в единицах значения в секунду, а не средняя скорость: барабан разгоняется и тормозит. " +
                 "При 45 путь 0 → 99 занимает около 3 с (по расчёту). На коротких сдвигах потолок почти не достигается, " +
                 "и время задаёт в основном smoothTime.")]
        public float rollSpeed = 45f;

        /// <summary>
        /// Время сглаживания для SmoothDamp: меньше значит резче и быстрее выход на цель.
        /// </summary>
        [Tooltip("Плавность (время сглаживания). Меньше — резче, больше — вальяжнее")]
        public float smoothTime = 0.18f;

        /// <summary>
        /// Насколько барабан выезжает за целевое значение перед возвратом, в долях одной цифры. 0 отключает выброс.
        /// </summary>
        [Tooltip("Выброс за цель в долях цифры, например 0.3 — это треть цифры. 0 отключает выброс. " +
                 "Выброс не выходит за пределы десятка цели, поэтому на целях вроде 9, 19 (вверх) и 10, 20 (вниз) его нет.")]
        public float overshoot = 0.3f;
    }
}
