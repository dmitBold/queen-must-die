namespace UI
{
    /// <summary>
    /// UI-элемент, который можно временно спрятать через UIManager.HideAll (HUD, подсказки, фонарик).
    /// Элементы, которые должны работать в катсценах и на загрузке (фейд, диалоги, экран загрузки), не регистрируются.
    /// </summary>
    public interface IUIHideable
    {
        /// <summary>
        /// Прячет или показывает элемент. Состояние элемента не сбрасывается, меняется только видимость.
        /// </summary>
        void SetHidden(bool hidden);
    }
}
